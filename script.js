async function streamAssistantAnswer() {
  const response = await fetch(ASSISTANT_ENDPOINT, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ model: "gemini-2.5-flash", stream: true, messages: [{ role: "system", content: assistantSystemPrompt() }, ...assistantHistory] })
  });
  if (!response.ok || !response.body) throw new Error(`Assistant unavailable: ${response.status}`);
  const message = addAssistantMessage("assistant", "");
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  let raw = "";
  let answer = "";
  while (true) {
    const { value, done } = await reader.read();
    buffer += decoder.decode(value || new Uint8Array(), { stream: !done });
    const lines = buffer.split("\n");
    buffer = lines.pop() || "";
    for (const line of lines) {
      if (!line.trim()) continue;
      const event = JSON.parse(line);
      if (event.message?.content) {
        raw += event.message.content;
        answer = cleanAssistantText(raw);
        message.textContent = answer;
        assistantMessages.scrollTop = assistantMessages.scrollHeight;
      }
    }
    if (done) break;
  }
  if (!answer) throw new Error("Empty assistant response");
  return answer;
}

