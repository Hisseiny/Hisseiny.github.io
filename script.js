const htmlKeys = new Set(["hero-title", "about-title"]);
const languageButtons = document.querySelectorAll("[data-lang]");
const menuButton = document.querySelector(".menu-toggle");
const mobileMenu = document.querySelector(".mobile-menu");
let activeLanguage = "en";

function setLanguage(language) {
  const lang = copy[language] ? language : "en";
  activeLanguage = lang;
  document.documentElement.lang = lang;
  document.title = copy[lang]["page-title"];
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[lang][key]) element.textContent = copy[lang][key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (htmlKeys.has(key) && copy[lang][key]) element.innerHTML = copy[lang][key];
  });
  languageButtons.forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.lang === lang)));
  menuButton.setAttribute("aria-label", copy[lang][menuButton.getAttribute("aria-expanded") === "true" ? "menu-close" : "menu-open"]);
  localStorage.setItem("portfolio-language", lang);
}

function setMenu(open) {
  menuButton.setAttribute("aria-expanded", String(open));
  menuButton.setAttribute("aria-label", copy[activeLanguage][open ? "menu-close" : "menu-open"]);
  mobileMenu.classList.toggle("open", open);
  mobileMenu.setAttribute("aria-hidden", String(!open));
  document.body.classList.toggle("menu-open", open);
}

languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.lang)));
menuButton.addEventListener("click", () => setMenu(menuButton.getAttribute("aria-expanded") !== "true"));
mobileMenu.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => setMenu(false)));
document.addEventListener("keydown", (event) => { if (event.key === "Escape") setMenu(false); });
setLanguage(localStorage.getItem("portfolio-language") || "en");

window.addEventListener("scroll", () => document.querySelector(".site-header").classList.toggle("scrolled", window.scrollY > 8), { passive: true });

document.querySelectorAll(".video-media").forEach((wrapper) => {
  const video = wrapper.querySelector("video");
  const button = wrapper.querySelector("button");
  button.addEventListener("click", async () => {
    if (video.paused) {
      await video.play();
      button.innerHTML = "<span>Pause</span>";
      button.setAttribute("aria-label", "Pause Oppy demonstration");
    } else {
      video.pause();
      button.innerHTML = "<span>Play</span>";
      button.setAttribute("aria-label", "Play Oppy demonstration");
    }
  });
});

document.querySelector("#current-year").textContent = new Date().getFullYear();
